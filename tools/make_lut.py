"""Generates Fragsmith's .cube LUT: a subtle teal-orange film look.

Run it again to adjust the look (change the constants below):
    python tools/make_lut.py

Designed to sit ON TOP of the eq/vibrance grade in edit_engine (which
already lifts contrast/saturation), so it's deliberately gentle:
- shadows are pulled toward teal (less red, a bit more blue/green)
- highlights are pulled toward warm/orange (more red, less blue)
- a mild S-curve for filmic contrast, soft shoulder so highlights don't clip
"""
from __future__ import annotations

from pathlib import Path

SIZE = 33               # standard .cube resolution (33³ points)
TEAL_SHADOW = 0.040     # how much the shadows are pulled toward teal
WARM_HIGHLIGHT = 0.035  # how much the highlights are pulled toward orange
S_CURVE = 0.10          # strength of the contrast S-curve (0 = off)

OUT = Path(__file__).resolve().parent.parent / "assets" / "luts" / (
    "fragsmith-teal-orange.cube"
)


def _s_curve(x: float) -> float:
    """Mild S-curve around 0.5: smoothstep blended in by S_CURVE."""
    smooth = x * x * (3.0 - 2.0 * x)
    return x + S_CURVE * (smooth - x)


def transform(r: float, g: float, b: float) -> tuple[float, float, float]:
    luma = 0.2126 * r + 0.7152 * g + 0.0722 * b
    ws = (1.0 - luma) ** 2   # shadow weight
    wh = luma ** 2           # highlight weight

    # split toning: teal in shadows (B/G up, R down), warmth in highlights
    r2 = r - TEAL_SHADOW * ws + WARM_HIGHLIGHT * wh
    g2 = g + 0.4 * TEAL_SHADOW * ws + 0.25 * WARM_HIGHLIGHT * wh
    b2 = b + TEAL_SHADOW * ws - WARM_HIGHLIGHT * wh

    out = tuple(_s_curve(min(1.0, max(0.0, c))) for c in (r2, g2, b2))
    return out  # type: ignore[return-value]


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "TITLE \"Fragsmith teal-orange (generated by tools/make_lut.py)\"",
        f"LUT_3D_SIZE {SIZE}",
        "DOMAIN_MIN 0.0 0.0 0.0",
        "DOMAIN_MAX 1.0 1.0 1.0",
    ]
    n = SIZE - 1
    # .cube order: red varies fastest, then green, then blue
    for bi in range(SIZE):
        for gi in range(SIZE):
            for ri in range(SIZE):
                r, g, b = transform(ri / n, gi / n, bi / n)
                lines.append(f"{r:.6f} {g:.6f} {b:.6f}")
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"Wrote {OUT} ({SIZE}^3 = {SIZE ** 3} points)")


if __name__ == "__main__":
    main()
